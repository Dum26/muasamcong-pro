const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('web/intelligence.js','utf8');
const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{value:'',textContent:'',innerHTML:'',hidden:false,disabled:false,classList:{toggle(){}}});return elements.get(id);};
const context=vm.createContext({document:{getElementById:get},URLSearchParams,Set,Date,Number,Math,encodeURIComponent,esc:value=>String(value??'').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]))});
vm.runInContext('const $=document.getElementById;'+source.slice(0,source.indexOf("document.querySelectorAll('[data-intel-tab]')")),context);
const row={tender_code:'IB2600123456',title:'Gói <thuốc>',investor_name:'Bệnh viện A',investor_id:'a'.repeat(32),status:'Chưa đóng thầu'};
const table=vm.runInContext('intelTable([globalThis.testRow])',Object.assign(context,{testRow:row}));
assert.match(table,/\/app\/tenders\/IB2600123456/);
assert.match(table,/\/app\/investors\/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa/);
assert.match(table,/Gói &lt;thuốc&gt;/);
assert.doesNotMatch(table,/Gói <thuốc>/);
const detail=vm.runInContext('intelDetailTabs(globalThis.testRow,{timeline:[],documents:[],changes:[],related:[]})',context);
assert.match(detail,/Chưa có mốc thời gian/);
assert.doesNotMatch(detail,/Mở thầu|Xét thầu/);
const chart=vm.runInContext("intelLine([{period:'2026-09',tenders:3},{period:'2026-10',tenders:7}])",context);
assert.match(chart,/polyline/);
assert.match(chart,/2026-10: 7 gói/);
assert.match(vm.runInContext('intelLine([])',context),/Chưa có ngày đăng/);
vm.runInContext('intelPager(101,2,50)',context);
assert.equal(get('intelPageLabel').textContent,'Trang 2/3 · 101 gói');
assert.equal(get('intelPrev').disabled,false);
assert.equal(get('intelNext').disabled,false);
console.log('PASS: intelligence links, safe HTML, factual timeline, charts and pagination');
