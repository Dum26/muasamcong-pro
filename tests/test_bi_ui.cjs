const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('web/bi.js','utf8');
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',textContent:'',hidden:false,classList:{toggle(){}}});return elements.get(id);};
const escape=value=>String(value??'').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const context=vm.createContext({document:{getElementById:element,querySelectorAll:()=>[]},
  URLSearchParams,Date,Set,Number,Math,encodeURIComponent,esc:escape,location:{pathname:'/app/analytics',search:''}});
vm.runInContext('const $=document.getElementById;'+source.slice(0,source.indexOf("\ndocument.querySelectorAll('[data-bi-tab]')")),context);
const range=vm.runInContext("biPeriodRange('2026-Q3')",context);
assert.equal(range.from,'2026-07-01');
assert.equal(range.to,'2026-09-30');
const preset=vm.runInContext("biPresetDates('last_year')",context);
assert.equal(preset.from.slice(5),'01-01');
assert.equal(preset.to.slice(5),'12-31');
const table=vm.runInContext("biTable([{tender_code:'IB2600123456',title:'<script>alert(1)</script>'}],['tender_code','title'])",context);
assert.match(table,/\/app\/tenders\/IB2600123456/);
assert.match(table,/&lt;script&gt;/);
assert.doesNotMatch(table,/<script>/);
const chart=vm.runInContext("biTrend([{period:'2026-09',tenders:4},{period:'2026-10',tenders:7}])",context);
assert.match(chart,/polyline/);
assert.match(chart,/Xem bảng số liệu biểu đồ/);
assert.match(chart,/data-bi-period="2026-10"/);
assert.match(vm.runInContext('biTrend([])',context),/Không có dữ liệu/);
vm.runInContext(`biState.reportSchema={datasets:{tenders:{fields:['tender_code','title','publish_date','package_price'],dates:['publish_date'],numeric:['package_price'],default_columns:['tender_code','title']}}};biState.filters={from:'2026-09-11',to:'2026-09-24'};`,context);
const filters=vm.runInContext("biBaseFilters('tenders')",context);
assert.equal(filters.length,2);
assert.equal(filters[0].value,'2026-09-11');
assert.equal(filters[1].value,'2026-09-25');
vm.runInContext("biState.reportSchema.datasets.deadlines={fields:['tender_code','title','bid_closing_date','publish_date'],dates:['bid_closing_date','publish_date'],default_columns:['tender_code','title','bid_closing_date']}",context);
const deadlineTemplate=vm.runInContext("biTemplate('deadlines')[0]",context);
assert.equal(deadlineTemplate.spec.sort.field,'bid_closing_date');
assert.equal(deadlineTemplate.spec.filters.filter(item=>item.field==='bid_closing_date').length,2);
assert.match(deadlineTemplate.spec.filters.find(item=>item.field==='bid_closing_date'&&item.operator==='after').value,/^\d{4}-\d{2}-\d{2}$/);
console.log('PASS: BI period drilldown, source links, safe HTML, chart table alternative and date filters');
